#!/usr/bin/env python3
"""Generate repo, website, and film identity assets from brand/tokens.json.

SVG lettering is outlined so GitHub and social previews need no installed fonts.
Run with --check to detect drift without writing files.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from xml.sax.saxutils import escape

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "brand"


def lettering(text: str, x: float, y: float, size: float, color: str, font: TTFont) -> str:
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    pen = SVGPathPen(glyphs)
    for char in text:
        glyph = glyphs[cmap[ord(char)]]
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, x, y)))
        x += glyph.width * scale
    return f'<path fill="{color}" d="{pen.getCommands()}"/>'


def wave(x: float, y: float, width: float, amp: float, color: str, step: int = 10) -> str:
    count = int(width / step)
    segments = []
    for i in range(count):
        p = i / count
        noise = math.sin(i * 12.9898 + 78.233) * 43758.545
        envelope = math.sin(p * math.pi) ** .6 * (.55 + .45 * abs(math.sin(p * 23 + 77)))
        h = max(2, amp * envelope * (.35 + .65 * (noise - math.floor(noise))))
        segments.append(f'M{x + i * step:.1f} {y - h:.1f}V{y + h:.1f}')
    return f'<path d="{"".join(segments)}" stroke="{color}" stroke-width="4" stroke-linecap="round"/>'


def svg(width: int, height: int, title: str, content: str) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title"><title id="title">{escape(title)}</title>{content}</svg>\n'


def outputs() -> dict[Path, str]:
    tokens = json.loads((BRAND / "tokens.json").read_text())
    colors = tokens["colors"]
    # This is the external-data boundary. Refuse malformed token values here.
    for key, value in colors.items():
        if len(value) != 7 or not value.startswith("#"):
            raise ValueError(f"Invalid color {key}: {value}")
        int(value[1:], 16)
    display = TTFont(BRAND / "fonts/InstrumentSerif-Regular.ttf")
    mono = TTFont(BRAND / "fonts/IBMPlexMono-Regular.ttf")
    bg, cream, ember, muted = (colors[k] for k in ("background", "cream", "ember", "muted"))
    rust_names = {"background": "BG", "panel": "PANEL", "line": "LINE", "cream": "CREAM", "muted": "DIM", "ember": "EMBER", "paper": "PAPER", "ink": "INK", "heading": "HEAD"}
    rust = "// Generated by marketing/scripts/brand.py. Edit brand/tokens.json.\n"
    rust += "".join(f'pub const {rust_names[k]}: &str = "{v}";\n' for k, v in colors.items())
    rust += f'pub const SERIF: &str = "{tokens["fonts"]["display"]}";\npub const MONO: &str = "{tokens["fonts"]["mono"]}";\n'
    css = "/* Generated by marketing/scripts/brand.py. Edit brand/tokens.json. */\n"
    css += """@font-face { font-family: 'Instrument Serif'; src: url('./fonts/InstrumentSerif-Regular.ttf') format('truetype'); font-weight: 400; font-style: normal; font-display: swap; }
@font-face { font-family: 'IBM Plex Mono'; src: url('./fonts/IBMPlexMono-Regular.ttf') format('truetype'); font-weight: 400; font-style: normal; font-display: swap; }
:root {\n"""
    css += "".join(f'  --ses-{k}: {v};\n' for k, v in colors.items())
    css += "  --ses-display: 'Instrument Serif', Georgia, serif;\n  --ses-mono: 'IBM Plex Mono', monospace;\n}\n"
    wordmark = lettering("ses", 2, 112, 160, cream, display)
    logo = svg(240, 140, "ses", wordmark)
    icon = svg(64, 64, "ses waveform", f'<rect width="64" height="64" rx="14" fill="{bg}"/>' + ''.join(f'<path d="M{x} {32-h}V{32+h}" stroke="{ember}" stroke-width="4" stroke-linecap="round"/>' for x, h in zip([14, 23, 32, 41, 50], [5, 13, 20, 10, 4])))
    banner = f'<rect width="1280" height="420" rx="16" fill="{bg}"/>'
    banner += lettering("ses", 64, 160, 172, cream, display)
    banner += lettering("Your script, in a cloned voice.", 68, 254, 56, cream, display)
    banner += lettering("VOICE SAMPLE + MARKDOWN", 70, 310, 17, muted, mono)
    banner += wave(840, 180, 360, 78, ember)
    banner += f'<path d="M68 358H1212" stroke="{colors["line"]}" stroke-width="2"/><path d="M68 358H720" stroke="{ember}" stroke-width="3"/><circle cx="720" cy="358" r="5" fill="{ember}"/>'
    social = f'<rect width="1200" height="630" fill="{bg}"/>'
    social += lettering("ses", 80, 222, 210, cream, display)
    social += lettering("Your script,", 84, 350, 78, cream, display)
    social += lettering("in a cloned voice.", 84, 433, 78, cream, display)
    social += wave(740, 280, 380, 104, ember)
    social += lettering("ses.apphane.dev", 84, 548, 23, ember, mono)
    social += f'<path d="M84 580H1116" stroke="{colors["line"]}" stroke-width="2"/><path d="M84 580H740" stroke="{ember}" stroke-width="3"/>'
    return {
        BRAND / "tokens.css": css,
        BRAND / "wordmark.svg": logo,
        BRAND / "icon.svg": icon,
        BRAND / "banner.svg": svg(1280, 420, "ses. Your script, in a cloned voice.", banner),
        BRAND / "social.svg": svg(1200, 630, "ses. Your script, in a cloned voice.", social),
        ROOT / "marketing/film/src/identity.rs": rust,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Stale brand assets: " + ", ".join(stale))
    print("Brand assets match tokens." if args.check else "Generated brand assets.")


if __name__ == "__main__":
    main()
